# VERBATIM copy of the generator fragment used for the CMS offline+scouting reference
# dataset (/eos/cms/store/cmst3/group/vhcc/ScoutingAK8/2024/train/), from the public
#   https://github.com/colizz/hww-tagging/tree/dev-miniaods/event_producer/cmsconnect_miniaods_scouting_Run3/fragments/QCD_PT-170to300_TuneCP5_13p6TeV_pythia8.py
# which is itself the official CMS McM Summer23GS fragment (see its own comment below).
#
# ONE adaptation for CMSSW_10_6_30, marked inline below: the Run-3 13.6 TeV CP5 tune
# module does not exist in this release (it ships only the 13 TeV MCTunes2017), so the
# import falls back to an inlined copy of that block from cms-sw/cmssw (Apache-2.0).
# The two differ only in SigmaTotal:sigmaEl/sigmaTot. Nothing else is changed.
#
# This process is generated by CMSSW itself in the GEN step - the presence of this
# `fragment.py` is what marks it as such (run.sh's PROC_KIND); it is FULLSIM-ONLY and
# the Delphes backend refuses it. The reference sample is "PT-mixed": these ten pThat
# bins generated with an EQUAL number of events each (500 jobs x 500 events = 250k per
# bin), i.e. flat in pThat rather than cross-section weighted - which is what makes its
# jet pT spectrum so hard. Reproduce that by submitting the SAME number of jobs for
# each jetclass2SB/QCD_PT-* process; see fullsim_configs/README.md.
#
# Beam energy is 13.6 TeV as in the reference, while the detector conditions are 2018
# (Run 2) - a deliberate choice, see fullsim_configs/README.md "Caveats".

# offical fragment https://cms-pdmv-prod.web.cern.ch/mcm/requests?page=0&dataset_name=QCD*&prepid=*Summer23GS*&shown=262271
# for profiling

import FWCore.ParameterSet.Config as cms

from Configuration.Generator.Pythia8CommonSettings_cfi import *
# --- adapted for CMSSW_10_6_30 (see this file's header) ---
try:
    from Configuration.Generator.MCTunesRun3ECM13p6TeV.PythiaCP5Settings_cfi import *
except ImportError:
    # cms-sw/cmssw Configuration/Generator/python/MCTunesRun3ECM13p6TeV/PythiaCP5Settings_cfi.py
    pythia8CP5SettingsBlock = cms.PSet(
        pythia8CP5Settings = cms.vstring(
            'Tune:pp 14', 'Tune:ee 7',
            'MultipartonInteractions:ecmPow=0.03344',
            'MultipartonInteractions:bProfile=2',
            'MultipartonInteractions:pT0Ref=1.41',
            'MultipartonInteractions:coreRadius=0.7634',
            'MultipartonInteractions:coreFraction=0.63',
            'ColourReconnection:range=5.176',
            'SigmaTotal:zeroAXB=off',
            'SpaceShower:alphaSorder=2', 'SpaceShower:alphaSvalue=0.118',
            'SigmaProcess:alphaSvalue=0.118', 'SigmaProcess:alphaSorder=2',
            'MultipartonInteractions:alphaSvalue=0.118',
            'MultipartonInteractions:alphaSorder=2',
            'TimeShower:alphaSorder=2', 'TimeShower:alphaSvalue=0.118',
            'SigmaTotal:mode = 0',
            'SigmaTotal:sigmaEl = 22.08', 'SigmaTotal:sigmaTot = 101.037',
            'PDF:pSet=LHAPDF6:NNPDF31_nnlo_as_0118',
        )
    )
# --- end adaptation ---

generator = cms.EDFilter("Pythia8ConcurrentGeneratorFilter",
	maxEventsToPrint = cms.untracked.int32(1),
	pythiaPylistVerbosity = cms.untracked.int32(1),
	filterEfficiency = cms.untracked.double(1.0),
	pythiaHepMCVerbosity = cms.untracked.bool(False),
	comEnergy = cms.double(13600.0),

	crossSection = cms.untracked.double(648.174),

	PythiaParameters = cms.PSet(
            pythia8CommonSettingsBlock,
            pythia8CP5SettingsBlock,
	    processParameters = cms.vstring(
			'HardQCD:all = on',
			'PhaseSpace:pTHatMin = 170  ',
			'PhaseSpace:pTHatMax = 300  ',
	    ),
            parameterSets = cms.vstring('pythia8CommonSettings',
                                        'pythia8CP5Settings',
                                        'processParameters',
                                        )
	)
)

configurationMetadata = cms.untracked.PSet(
    version = cms.untracked.string('\$Revision$'),
    name = cms.untracked.string('\$Source$'),
    annotation = cms.untracked.string('QCD pthat 170to300 GeV, 13.6 TeV, TuneCP5')
)
