# ADAPTED copy of the generator fragment used for the CMS offline+scouting reference
# dataset (/eos/cms/store/cmst3/group/vhcc/ScoutingAK8/2024/train/), from the public
#   https://github.com/colizz/hww-tagging/tree/dev-miniaods/event_producer/cmsconnect_miniaods_scouting_Run3/fragments/QCD_PT-1400to1800_TuneCP5_13p6TeV_pythia8.py
# which is itself the official CMS McM Summer23GS fragment (see its own comment below).
#
# TWO deliberate departures from the reference, both so the generation matches the
# 2018 (Run 2) detector conditions this repository simulates with:
#
#   * comEnergy is 13 TeV, not the reference's 13.6 TeV. Run 2 ran at 13 TeV, and the
#     jetclass2 signal is generated at 13 TeV as well (MadGraph's default 6500 GeV
#     beams), so this is what makes signal, background and conditions consistent with
#     one another. The reference remains a 13.6 TeV Run-3 sample; comparisons against
#     it are therefore across beam energies - see gen_configs/jetclass2sb/README.md.
#   * the CP5 tune is the 13 TeV one (Configuration.Generator.MCTunes2017), not the
#     Run-3 13.6 TeV retune. CP5 is tuned PER BEAM ENERGY, so changing comEnergy
#     without changing the tune would be only half the fix. The two blocks differ in
#     SigmaTotal:sigmaEl/sigmaTot (21.89/100.309 here, 22.08/101.037 at 13.6 TeV).
#     CMSSW_10_6_30 ships the 13 TeV module natively, so the inlined copy that used to
#     stand in for the missing Run-3 one is gone.
#
# This process is generated by CMSSW itself in the GEN step - the presence of this
# `fragment.py` is what marks it as such (run.sh's PROC_KIND); it is FULLSIM-ONLY and
# the Delphes backend refuses it. The reference sample is "PT-mixed": these ten pThat
# bins generated with an EQUAL number of events each (500 jobs x 500 events = 250k per
# bin), i.e. flat in pThat rather than cross-section weighted - which is what makes its
# jet pT spectrum so hard. Reproduce that by submitting the SAME number of jobs for
# each jetclass2sb/QCD_PT-* process; see fullsim_configs/README.md.
#
# Beam energy (13 TeV) and detector conditions (2018, Run 2) now agree - see
# fullsim_configs/README.md "Caveats".

# offical fragment https://cms-pdmv-prod.web.cern.ch/mcm/requests?page=0&dataset_name=QCD*&prepid=*Summer23GS*&shown=262271
# for profiling

import FWCore.ParameterSet.Config as cms

from Configuration.Generator.Pythia8CommonSettings_cfi import *
# 13 TeV CP5, not the reference's Run-3 13.6 TeV retune - see this file's header
from Configuration.Generator.MCTunes2017.PythiaCP5Settings_cfi import *

generator = cms.EDFilter("Pythia8ConcurrentGeneratorFilter",
	maxEventsToPrint = cms.untracked.int32(1),
	pythiaPylistVerbosity = cms.untracked.int32(1),
	filterEfficiency = cms.untracked.double(1.0),
	pythiaHepMCVerbosity = cms.untracked.bool(False),
	comEnergy = cms.double(13000.0),

	# dummy value, not used anywhere: this is untracked metadata that only fills
	# GenRunInfoProduct's external cross section. It never affects generation, and
	# nothing in this repository reads it - we generate a FLAT mixture (equal events
	# per pThat bin), not a cross-section-weighted one. The reference's own values
	# were copy-paste artifacts anyway: 648.174 appeared in eight bins spanning
	# pThat 170-3200 GeV, where the true cross section falls by ~6 orders of magnitude.
	crossSection = cms.untracked.double(1),

	PythiaParameters = cms.PSet(
            pythia8CommonSettingsBlock,
            pythia8CP5SettingsBlock,
	    processParameters = cms.vstring(
			'HardQCD:all = on',
			'PhaseSpace:pTHatMin = 1400  ',
			'PhaseSpace:pTHatMax = 1800  ',
	    ),
            parameterSets = cms.vstring('pythia8CommonSettings',
                                        'pythia8CP5Settings',
                                        'processParameters',
                                        )
	)
)

configurationMetadata = cms.untracked.PSet(
    version = cms.untracked.string('\$Revision$'),
    name = cms.untracked.string('\$Source$'),
    annotation = cms.untracked.string('QCD pthat 1400to1800 GeV, 13 TeV, TuneCP5')
)
